"""Data before C++ exception-handling functions.

MSVC for Xbox 360 puts 8 bytes in .text right before every function whose
.pdata entry has the ExceptionFlag bit: the language handler's address (in
.text) and its handler data (in .rdata/.data). XenonRecomp decodes those words
as code and makes an overlapping bogus function, whose jump tables then
"jump outside" it. This writes them as data_ranges.

    SB_GAME=hp5 python3 survey/eh_data_ranges.py          # report
    SB_GAME=hp5 python3 survey/eh_data_ranges.py --write  # update the config
"""
import struct, sys
sys.path.insert(0, 'survey')
from games import G

BASE = 0x82000000
img = open(G['survey'] + '/image.bin', 'rb').read()


def word(a):
    return struct.unpack('>I', img[a - BASE:a - BASE + 4])[0]


def in_text(v):
    return G['text'][0] <= v < G['text'][1]


def in_data(v):
    return any(lo <= v < hi for lo, hi in G['data'])


ranges, odd = [], []
for a in range(G['pdata'][0], G['pdata'][1], 8):
    begin, info = word(a), word(a + 4)
    if not begin or not (info >> 31) & 1:
        continue
    handler, hdata = word(begin - 8), word(begin - 4)
    if in_text(handler) and in_data(hdata):
        ranges.append(begin - 8)
    else:
        odd.append((begin, handler, hdata))

print(f'{len(ranges)} exception-handler headers, {len(odd)} without one', file=sys.stderr)
for begin, handler, hdata in odd:
    print(f'#   0x{begin:08X}: words 0x{handler:08X} 0x{hdata:08X} (not handler + data)', file=sys.stderr)

START = '    # --- generated by survey/eh_data_ranges.py --write ---\n'
END = '    # --- end eh_data_ranges ---\n'
block = START + ''.join(f'    {{ address = 0x{r:08X}, size = 0x8 }},\n' for r in ranges) + END

if '--write' in sys.argv:
    cfg = open(G['config']).read()
    if START in cfg:
        head, rest = cfg.split(START, 1)
        cfg = head + block + rest.split(END, 1)[1]
    else:
        cfg = cfg.replace('data_ranges = [\n', 'data_ranges = [\n' + block, 1)
    open(G['config'], 'w').write(cfg)
    print('wrote ' + G['config'], file=sys.stderr)
else:
    sys.stdout.write(block)
